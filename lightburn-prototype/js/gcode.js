// LightBurn Prototype - CAM & G-Code Generation Engine

import { MACHINE_DEFAULTS } from './constants.js';

export class GCodeGenerator {
    constructor(machineConfig = MACHINE_DEFAULTS) {
        this.config = { ...MACHINE_DEFAULTS, ...machineConfig };
    }

    /**
     * Converts canvas Y coordinates to machine coordinates based on the origin corner setting.
     */
    transformCoordinates(x, y) {
        let machineX = x;
        let machineY = y;

        if (this.config.originCorner === 'Bottom-Left') {
            // Canvas Y=0 is top, so Y_machine = bedHeight - y
            machineY = this.config.bedHeight - y;
        } else if (this.config.originCorner === 'Top-Right') {
            machineX = this.config.bedWidth - x;
        } else if (this.config.originCorner === 'Bottom-Right') {
            machineX = this.config.bedWidth - x;
            machineY = this.config.bedHeight - y;
        }
        // Top-Left: standard canvas coordinates

        return {
            x: Math.round(machineX * 100) / 100,
            y: Math.round(machineY * 100) / 100
        };
    }

    /**
     * Generate complete G-code string and kinematic metrics from shapes and layer definitions.
     */
    generate(shapes, layerManager) {
        const lines = [];
        let totalRapidDist = 0; // mm
        let totalCutDist = 0;   // mm
        let currentPos = { x: 0, y: 0 }; // Initial machine head position

        // Header
        const now = new Date().toISOString();
        lines.push('; ========================================================');
        lines.push('; Generated by LightBurn Prototype CAM Engine');
        lines.push(`; Timestamp: ${now}`);
        lines.push(`; Bed Size: ${this.config.bedWidth} x ${this.config.bedHeight} mm`);
        lines.push(`; Origin: ${this.config.originCorner}`);
        lines.push('; ========================================================');
        lines.push('G21          ; Set units to millimeters');
        lines.push('G90          ; Absolute coordinates mode');
        lines.push('M5           ; Ensure laser is off');
        lines.push(`G0 F${this.config.rapidFeedRate} ; Set rapid feedrate`);
        lines.push('G0 X0 Y0     ; Rapid to origin');
        lines.push('');

        // Sort layers: Fills first, then Lines (Engrave before Cut)
        const activeLayers = layerManager.layers
            .filter(l => l.output && l.mode !== 'Tool')
            .sort((a, b) => {
                const order = { 'Fill': 1, 'Fill+Line': 2, 'Line': 3 };
                return (order[a.mode] || 4) - (order[b.mode] || 4);
            });

        for (const layer of activeLayers) {
            const layerShapes = shapes.filter(s => s.layerId === layer.id);
            if (layerShapes.length === 0) continue;

            const pwmPower = Math.round((layer.power / 100) * this.config.maxPower);
            const speed = layer.speed;
            const laserCmd = this.config.laserMode === 'GRBL-M4' ? 'M4' : 'M3';

            lines.push(`; --------------------------------------------------------`);
            lines.push(`; LAYER ${layer.code}: "${layer.name}"`);
            lines.push(`; Mode: ${layer.mode} | Speed: ${speed} mm/min | Power: ${layer.power}% (S${pwmPower}) | Passes: ${layer.passes}`);
            lines.push(`; --------------------------------------------------------`);

            if (layer.airAssist) {
                lines.push('M8           ; Air assist ON');
            }

            for (let pass = 1; pass <= layer.passes; pass++) {
                if (layer.passes > 1) {
                    lines.push(`; --- Pass ${pass} of ${layer.passes} ---`);
                }

                // 1. Process FILL / Engrave Raster
                if (layer.mode === 'Fill' || layer.mode === 'Fill+Line') {
                    for (const shape of layerShapes) {
                        const rasterSegments = shape.generateRasterLines(layer.interval || 0.1);
                        if (rasterSegments.length === 0) continue;

                        lines.push(`; Engrave Raster for ${shape.name} (${rasterSegments.length} scanlines)`);

                        for (const seg of rasterSegments) {
                            const p1 = this.transformCoordinates(seg.x1, seg.y1);
                            const p2 = this.transformCoordinates(seg.x2, seg.y2);

                            // Rapid move to start of raster line
                            const rapidDist = Math.hypot(p1.x - currentPos.x, p1.y - currentPos.y);
                            totalRapidDist += rapidDist;
                            lines.push(`G0 X${p1.x} Y${p1.y}`);
                            currentPos = p1;

                            // Laser ON and burn across
                            lines.push(`${laserCmd} S${pwmPower}`);
                            const cutDist = Math.hypot(p2.x - p1.x, p2.y - p1.y);
                            totalCutDist += cutDist;
                            lines.push(`G1 X${p2.x} Y${p2.y} F${speed}`);
                            lines.push('M5           ; Laser OFF');
                            currentPos = p2;
                        }
                    }
                }

                // 2. Process LINE / Vector Cut
                if (layer.mode === 'Line' || layer.mode === 'Fill+Line') {
                    for (const shape of layerShapes) {
                        const polylines = shape.toPolylines();
                        lines.push(`; Vector Path for ${shape.name}`);

                        for (const poly of polylines) {
                            if (poly.length < 2) continue;

                            const startPt = this.transformCoordinates(poly[0].x, poly[0].y);

                            // Rapid to start of polyline
                            const rapidDist = Math.hypot(startPt.x - currentPos.x, startPt.y - currentPos.y);
                            totalRapidDist += rapidDist;
                            lines.push(`G0 X${startPt.x} Y${startPt.y}`);
                            currentPos = startPt;

                            // Turn laser ON
                            lines.push(`${laserCmd} S${pwmPower}`);

                            // Cut along vertices
                            for (let i = 1; i < poly.length; i++) {
                                const pt = this.transformCoordinates(poly[i].x, poly[i].y);
                                const cutDist = Math.hypot(pt.x - currentPos.x, pt.y - currentPos.y);
                                totalCutDist += cutDist;
                                lines.push(`G1 X${pt.x} Y${pt.y} F${speed}`);
                                currentPos = pt;
                            }

                            // Turn laser OFF
                            lines.push('M5           ; Laser OFF');
                        }
                    }
                }
            }

            if (layer.airAssist) {
                lines.push('M9           ; Air assist OFF');
            }
            lines.push('');
        }

        // Footer
        lines.push('; ========================================================');
        lines.push('; Job Completion & Return to Safe Home');
        lines.push('M5           ; Laser OFF');
        lines.push('M9           ; Air assist OFF');
        lines.push('G0 X0 Y0     ; Return to origin');
        lines.push('M2           ; Program end');
        lines.push('; ========================================================');

        // Estimate time:
        // Cut time = CutDist / Speed (speed in mm/min -> divide by 60 for seconds)
        // Rapid time = RapidDist / RapidFeed
        // Acceleration overhead penalty approx 15%
        const avgCutSpeed = 1500; // default baseline mm/min
        const cutTimeSec = (totalCutDist / (avgCutSpeed / 60)) * 1.15;
        const rapidTimeSec = (totalRapidDist / (this.config.rapidFeedRate / 60)) * 1.15;
        const totalEstimatedSec = Math.max(1, Math.round(cutTimeSec + rapidTimeSec));

        const mins = Math.floor(totalEstimatedSec / 60);
        const secs = totalEstimatedSec % 60;
        const formattedTime = `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;

        return {
            gcode: lines.join('\n'),
            totalLines: lines.length,
            totalCutDist: Math.round(totalCutDist * 10) / 10,
            totalRapidDist: Math.round(totalRapidDist * 10) / 10,
            estimatedSeconds: totalEstimatedSec,
            formattedTime: formattedTime
        };
    }
}
